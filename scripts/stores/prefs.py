@dataclass(frozen=True)
class Pref:
    name: str      # 愛知県
    code: int      # 23
    bounds: tuple  # (南, 西, 北, 東)

    @property
    def code2(self):  # "23"
        return f"{self.code:02d}"

    @property
    def romaji(self):  # aichi
        return ROMAJI[self.code - 1]

    @property
    def short(self):  # 愛知（北海道はそのまま）
        return self.name if self.name == "北海道" else self.name[:-1]


PREFS = {name: Pref(name, i + 1, (s - 0.1, w - 0.1, n + 0.1, e + 0.1)) for i, (name, s, w, n, e) in enumerate(_DATA)}


def pref_of_address(addr):
    """住所の先頭の都道府県名（なければ None）"""
    for name in PREFS:
        if addr.startswith(name):
            return name
    return None


def find(name):
    """「愛知」「愛知県」「大阪」などから Pref を探す"""
    name = (name or "").strip()
    if name in PREFS:
        return PREFS[name]
    for p in PREFS.values():
        if p.short == name:
            return p
    return None
